/** Татарский тюльпан (лалә) по сетке: r — лепесток, y — золото, g — стебель и листья. */
private val TULIP_M = arrayOf(
    "......r......",
    ".....rrr.....",
    "..r..rrr..r..",
    "..rr.ryr.rr..",
    "..rrrryrrrr..",
    "..rrryyyrrr..",
    "...rrryrrr...",
    "....rrrrr....",
    "......g......",
    ".gg...g...gg.",
    "gggg..g..gggg",
    ".gggg.g.gggg.",
    "...ggggggg...")
/** Ромбик-«звёздочка» между тюльпанами. */
private val STAR_M = arrayOf(".....", "..y..", ".yry.", "..y..", ".....")

private fun DrawScope.stitchC(m: Array<String>, x: Float, y: Float, cell: Float) {
    for (j in m.indices) for (i in m[j].indices) {
        val col = when (m[j][i]) { 'r' -> TULIP; 'y' -> PINK; 'g' -> RED; else -> null } ?: continue
        drawRect(col, Offset(x + i * cell, y + j * cell), Size(cell + 0.5f, cell + 0.5f))
    }
}

/** Кайма: зелёная полоса, тонкая золотая нить и ряд тюльпанов с золотыми ромбиками (татарский растительный орнамент). */
@Composable
fun Kaima(modifier: Modifier = Modifier.fillMaxWidth(), cell: Dp = 3.dp, bar: Dp = 2.dp) {
    val c0 = cell * 0.62f
    val h = bar * 2 + c0 * 15f
    Canvas(modifier.height(h)) {
        val c = c0.toPx(); val b = bar.toPx()
        drawRect(RED, Offset.Zero, Size(size.width, b))
        drawRect(PINK, Offset(0f, b * 1.4f), Size(size.width, b * 0.45f))
        val tw = TULIP_M[0].length * c; val sw = STAR_M[0].length * c; val unit = tw + sw
        val n = (size.width / unit).toInt() + 2; val x0 = (size.width - n * unit) / 2
        val y0 = b * 2 + c
        for (k in 0 until n) {
            val x = x0 + k * unit
            stitchC(TULIP_M, x, y0, c)
            stitchC(STAR_M, x + tw, y0 + c * 4, c)
        }
    }
}

/** Вертикальная кайма-меандр: красная полоса с «холщовыми» крючками. */
@Composable
fun MeanderEdge(modifier: Modifier, flip: Boolean = false) {
    Canvas(modifier) {
        drawRect(RED)
        val m = Motifs.MEANDER; val cell = size.width / (m[0].length + 1)
        var y = 0f; while (y < size.height) { stitch(m, cell * 0.5f, y, cell, LINEN, flip); y += m.size * cell }
    }
}

/** Нижний край: тонкая повторная кайма (бахромы нет). */
@Composable
fun TowelEnd(modifier: Modifier = Modifier.fillMaxWidth(), cellDp: Dp = 1.6.dp, fringe: Boolean = false) {
    Kaima(modifier, cell = 1.8.dp, bar = 1.5.dp)
}

/** Заливка холстом (для drawBehind). */
fun DrawScope.linenFill() {
    drawRect(LINEN); if (true) return
    val step = 3.dp.toPx(); val c = LINEN_D.copy(alpha = 0.45f)
    var x = 0f; while (x < size.width) { drawLine(c, Offset(x, 0f), Offset(x, size.height), 0.6f); x += step }
    var y = 0f; while (y < size.height) { drawLine(c.copy(alpha = 0.3f), Offset(0f, y), Offset(size.width, y), 0.6f); y += step }
}

/** Кайма-меандр по левому и правому краю (для drawBehind). */
fun DrawScope.meanderEdges(edge: Float, top: Float = 0f) {
    if (true) return
    val m = Motifs.MEANDER; val cell = edge / (m[0].length + 1)
    for (side in 0..1) {
        val x0 = if (side == 0) 0f else size.width - edge
        drawRect(RED, Offset(x0, top), Size(edge, size.height - top))
        var y = top; while (y < size.height) { stitch(m, x0 + cell * 0.5f, y, cell, LINEN, side == 1); y += m.size * cell }
    }
}
