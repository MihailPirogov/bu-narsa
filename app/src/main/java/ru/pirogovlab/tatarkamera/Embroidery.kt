fun DrawScope.stitch(m: Array<String>, x: Float, y: Float, cell: Float, color: Color, flip: Boolean = false) {
    val w = m[0].length
    for (j in m.indices) { val r = m[j]; for (i in r.indices) if (r[i] == '#') {
        val ii = if (flip) w - 1 - i else i
        drawRect(color, Offset(x + ii * cell, y + j * cell), Size(cell + 0.5f, cell + 0.5f)) } }
}

/** Одиночный мотив (розетка и т. п.), вписан в размер. */
@Composable
fun Motif(m: Array<String>, modifier: Modifier, color: Color = RED) {
    Canvas(modifier) {
        val cell = minOf(size.width / m[0].length, size.height / m.size)
        stitch(m, (size.width - cell * m[0].length) / 2, (size.height - cell * m.size) / 2, cell, color)
    }
}

/** Фактура льняного холста. */
@Composable
fun Linen(modifier: Modifier) {
    Canvas(modifier) {
        drawRect(LINEN)
        val step = 3.dp.toPx(); val c = LINEN_D.copy(alpha = 0.45f)
        var x = 0f; while (x < size.width) { drawLine(c, Offset(x, 0f), Offset(x, size.height), 0.6f); x += step }
        var y = 0f; while (y < size.height) { drawLine(c.copy(alpha = 0.3f), Offset(0f, y), Offset(size.width, y), 0.6f); y += step }
    }
}

